test('API outage remains a visible failure, not a fake login', async ({ page }) => {
  await page.goto('/login')
  await page.route('**/api/auth/otp', route => route.abort('failed'))
  await page.getByLabel('Adresse e-mail').fill('outage@example.com')
  await page.getByRole('button', { name: 'Recevoir mon code' }).click()
  await expect(page.getByRole('alert')).toContainText('Impossible')
  await expect(page).toHaveURL(/\/login$/)
  expect(await page.evaluate(() => localStorage.getItem('root404_token'))).toBeNull()
})

